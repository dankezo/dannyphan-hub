// Merge a (possibly partial) stats object over the snapshot, so a missing
// field in Turso never produces "undefined" in Neo's mouth.
export function withStatsFallback(stats) {
  const s = stats && typeof stats === 'object' ? stats : {};
  const base = NEO_STATS_SNAPSHOT;
  return {
    generated_at: s.generated_at || base.generated_at,
    antirea: Object.assign({}, base.antirea, s.antirea || {}),
    baoan: Object.assign({}, base.baoan, s.baoan || {}),
    warnings_sent: s.warnings_sent != null ? s.warnings_sent : base.warnings_sent,
    bounty_prs_open: s.bounty_prs_open != null ? s.bounty_prs_open : base.bounty_prs_open,
    lab: Object.assign({}, base.lab, s.lab || {}),
    projects: Array.isArray(s.projects) && s.projects.length ? s.projects : base.projects,
  };
}

